AidlCameraMetadata buildStaticCharacteristics(const CameraStaticConfig& cfg) {
    MetaBuilder b(96, 4096);

    const uint8_t offU8 = ANDROID_COLOR_CORRECTION_ABERRATION_MODE_OFF;
    b.add(ANDROID_COLOR_CORRECTION_AVAILABLE_ABERRATION_MODES, &offU8, 1);

    const uint8_t antibanding[] = {
        ANDROID_CONTROL_AE_ANTIBANDING_MODE_OFF,
        ANDROID_CONTROL_AE_ANTIBANDING_MODE_50HZ,
        ANDROID_CONTROL_AE_ANTIBANDING_MODE_60HZ,
        ANDROID_CONTROL_AE_ANTIBANDING_MODE_AUTO,
    };
    b.add(ANDROID_CONTROL_AE_AVAILABLE_ANTIBANDING_MODES, antibanding, sizeof(antibanding));

    std::vector<uint8_t> aeModes = {
        ANDROID_CONTROL_AE_MODE_OFF,
        ANDROID_CONTROL_AE_MODE_ON,
    };
    if (cfg.hasFlash) {
        aeModes.push_back(ANDROID_CONTROL_AE_MODE_ON_AUTO_FLASH);
        aeModes.push_back(ANDROID_CONTROL_AE_MODE_ON_ALWAYS_FLASH);
    }
    b.add(ANDROID_CONTROL_AE_AVAILABLE_MODES, aeModes.data(), aeModes.size());

    const int32_t fpsRanges[] = {15, 30, 30, 30};
    b.add(ANDROID_CONTROL_AE_AVAILABLE_TARGET_FPS_RANGES, fpsRanges, 4);

    const int32_t evRange[] = {-6, 6};
    b.add(ANDROID_CONTROL_AE_COMPENSATION_RANGE, evRange, 2);
    const camera_metadata_rational_t evStep = {1, 3};
    b.addOne(ANDROID_CONTROL_AE_COMPENSATION_STEP, evStep);
    b.addU8(ANDROID_CONTROL_AE_LOCK_AVAILABLE, ANDROID_CONTROL_AE_LOCK_AVAILABLE_TRUE);

    std::vector<uint8_t> afModes = {ANDROID_CONTROL_AF_MODE_OFF};
    if (cfg.hasAutofocus) {
        afModes.push_back(ANDROID_CONTROL_AF_MODE_AUTO);
        afModes.push_back(ANDROID_CONTROL_AF_MODE_MACRO);
        afModes.push_back(ANDROID_CONTROL_AF_MODE_CONTINUOUS_VIDEO);
        afModes.push_back(ANDROID_CONTROL_AF_MODE_CONTINUOUS_PICTURE);
    }
    b.add(ANDROID_CONTROL_AF_AVAILABLE_MODES, afModes.data(), afModes.size());

    b.addU8(ANDROID_CONTROL_AVAILABLE_EFFECTS, ANDROID_CONTROL_EFFECT_MODE_OFF);
    const uint8_t ctrlModes[] = {ANDROID_CONTROL_MODE_OFF, ANDROID_CONTROL_MODE_AUTO};
    b.add(ANDROID_CONTROL_AVAILABLE_MODES, ctrlModes, sizeof(ctrlModes));
    b.addU8(ANDROID_CONTROL_AVAILABLE_SCENE_MODES, ANDROID_CONTROL_SCENE_MODE_DISABLED);
    b.addU8(ANDROID_CONTROL_AVAILABLE_VIDEO_STABILIZATION_MODES, ANDROID_CONTROL_VIDEO_STABILIZATION_MODE_OFF);

    const uint8_t awbModes[] = {
        ANDROID_CONTROL_AWB_MODE_OFF,
        ANDROID_CONTROL_AWB_MODE_AUTO,
        ANDROID_CONTROL_AWB_MODE_INCANDESCENT,
        ANDROID_CONTROL_AWB_MODE_FLUORESCENT,
        ANDROID_CONTROL_AWB_MODE_DAYLIGHT,
        ANDROID_CONTROL_AWB_MODE_CLOUDY_DAYLIGHT,
    };
    b.add(ANDROID_CONTROL_AWB_AVAILABLE_MODES, awbModes, sizeof(awbModes));
    b.addU8(ANDROID_CONTROL_AWB_LOCK_AVAILABLE, ANDROID_CONTROL_AWB_LOCK_AVAILABLE_TRUE);

    const int32_t maxRegions[] = {1, 0, cfg.hasAutofocus ? 1 : 0};
    b.add(ANDROID_CONTROL_MAX_REGIONS, maxRegions, 3);
    const float zoomRange[] = {1.0f, 4.0f};
    b.add(ANDROID_CONTROL_ZOOM_RATIO_RANGE, zoomRange, 2);

    const uint8_t edgeModes[] = {ANDROID_EDGE_MODE_OFF, ANDROID_EDGE_MODE_FAST};
    b.add(ANDROID_EDGE_AVAILABLE_EDGE_MODES, edgeModes, sizeof(edgeModes));

    b.addU8(ANDROID_FLASH_INFO_AVAILABLE,
            cfg.hasFlash ? ANDROID_FLASH_INFO_AVAILABLE_TRUE : ANDROID_FLASH_INFO_AVAILABLE_FALSE);

    b.addU8(ANDROID_INFO_SUPPORTED_HARDWARE_LEVEL, ANDROID_INFO_SUPPORTED_HARDWARE_LEVEL_LIMITED);

    const int32_t thumbSizes[] = {0, 0, 320, 180, 320, 240};
    b.add(ANDROID_JPEG_AVAILABLE_THUMBNAIL_SIZES, thumbSizes, 6);
    b.addI32(ANDROID_JPEG_MAX_SIZE, cfg.maxJpegSize);

    b.addU8(ANDROID_LENS_FACING, cfg.isFront ? ANDROID_LENS_FACING_FRONT : ANDROID_LENS_FACING_BACK);
    b.addF32(ANDROID_LENS_INFO_AVAILABLE_APERTURES, cfg.apertureF);
    b.addF32(ANDROID_LENS_INFO_AVAILABLE_FILTER_DENSITIES, 0.0f);
    b.addF32(ANDROID_LENS_INFO_AVAILABLE_FOCAL_LENGTHS, cfg.focalLengthMm);
    b.addU8(ANDROID_LENS_INFO_AVAILABLE_OPTICAL_STABILIZATION, ANDROID_LENS_OPTICAL_STABILIZATION_MODE_OFF);
    b.addU8(ANDROID_LENS_INFO_FOCUS_DISTANCE_CALIBRATION,
            ANDROID_LENS_INFO_FOCUS_DISTANCE_CALIBRATION_UNCALIBRATED);
    b.addF32(ANDROID_LENS_INFO_MINIMUM_FOCUS_DISTANCE, cfg.hasAutofocus ? cfg.minFocusDistance : 0.0f);

    const uint8_t nrModes[] = {ANDROID_NOISE_REDUCTION_MODE_OFF, ANDROID_NOISE_REDUCTION_MODE_FAST};
    b.add(ANDROID_NOISE_REDUCTION_AVAILABLE_NOISE_REDUCTION_MODES, nrModes, sizeof(nrModes));

    const uint8_t caps[] = {ANDROID_REQUEST_AVAILABLE_CAPABILITIES_BACKWARD_COMPATIBLE};
    b.add(ANDROID_REQUEST_AVAILABLE_CAPABILITIES, caps, sizeof(caps));
    b.addI32(ANDROID_REQUEST_MAX_NUM_INPUT_STREAMS, 0);
    const int32_t maxOut[] = {0, 2, 1};
    b.add(ANDROID_REQUEST_MAX_NUM_OUTPUT_STREAMS, maxOut, 3);
    b.addI32(ANDROID_REQUEST_PARTIAL_RESULT_COUNT, 1);
    b.addU8(ANDROID_REQUEST_PIPELINE_MAX_DEPTH, 4);

    b.addF32(ANDROID_SCALER_AVAILABLE_MAX_DIGITAL_ZOOM, 4.0f);

    std::vector<int32_t> streamConfigs;
    std::vector<int64_t> minDurations;
    std::vector<int64_t> stallDurations;
    streamConfigs.reserve(cfg.streams.size() * 4);
    minDurations.reserve(cfg.streams.size() * 4);
    stallDurations.reserve(cfg.streams.size() * 4);
    for (const auto& s : cfg.streams) {
        streamConfigs.push_back(s.format);
        streamConfigs.push_back(s.width);
        streamConfigs.push_back(s.height);
        streamConfigs.push_back(ANDROID_SCALER_AVAILABLE_STREAM_CONFIGURATIONS_OUTPUT);

        minDurations.push_back(s.format);
        minDurations.push_back(s.width);
        minDurations.push_back(s.height);
        minDurations.push_back(s.minFrameDurationNs);

        stallDurations.push_back(s.format);
        stallDurations.push_back(s.width);
        stallDurations.push_back(s.height);
        stallDurations.push_back(s.stallDurationNs);
    }
    b.add(ANDROID_SCALER_AVAILABLE_STREAM_CONFIGURATIONS, streamConfigs.data(), streamConfigs.size());
    b.add(ANDROID_SCALER_AVAILABLE_MIN_FRAME_DURATIONS, minDurations.data(), minDurations.size());
    b.add(ANDROID_SCALER_AVAILABLE_STALL_DURATIONS, stallDurations.data(), stallDurations.size());
    b.addU8(ANDROID_SCALER_CROPPING_TYPE, ANDROID_SCALER_CROPPING_TYPE_CENTER_ONLY);

    b.addI32(ANDROID_SENSOR_AVAILABLE_TEST_PATTERN_MODES, ANDROID_SENSOR_TEST_PATTERN_MODE_OFF);
    const int32_t activeRect[] = {0, 0, cfg.activeWidth, cfg.activeHeight};
    b.add(ANDROID_SENSOR_INFO_ACTIVE_ARRAY_SIZE, activeRect, 4);
    const int64_t expoRange[] = {100000LL, 500000000LL};
    b.add(ANDROID_SENSOR_INFO_EXPOSURE_TIME_RANGE, expoRange, 2);
    b.addI64(ANDROID_SENSOR_INFO_MAX_FRAME_DURATION, 500000000LL);
    const float physSize[] = {cfg.physicalWidthMm, cfg.physicalHeightMm};
    b.add(ANDROID_SENSOR_INFO_PHYSICAL_SIZE, physSize, 2);
    const int32_t pixelArr[] = {cfg.activeWidth, cfg.activeHeight};
    b.add(ANDROID_SENSOR_INFO_PIXEL_ARRAY_SIZE, pixelArr, 2);
    const int32_t isoRange[] = {50, 1600};
    b.add(ANDROID_SENSOR_INFO_SENSITIVITY_RANGE, isoRange, 2);
    b.addU8(ANDROID_SENSOR_INFO_TIMESTAMP_SOURCE, ANDROID_SENSOR_INFO_TIMESTAMP_SOURCE_UNKNOWN);
    b.addI32(ANDROID_SENSOR_ORIENTATION, cfg.sensorOrientation);

    b.addU8(ANDROID_SHADING_AVAILABLE_MODES, ANDROID_SHADING_MODE_OFF);
    b.addU8(ANDROID_STATISTICS_INFO_AVAILABLE_FACE_DETECT_MODES, ANDROID_STATISTICS_FACE_DETECT_MODE_OFF);
    b.addU8(ANDROID_STATISTICS_INFO_AVAILABLE_HOT_PIXEL_MAP_MODES, ANDROID_STATISTICS_HOT_PIXEL_MAP_MODE_OFF);
    b.addU8(ANDROID_STATISTICS_INFO_AVAILABLE_LENS_SHADING_MAP_MODES,
            ANDROID_STATISTICS_LENS_SHADING_MAP_MODE_OFF);
    b.addI32(ANDROID_STATISTICS_INFO_MAX_FACE_COUNT, 0);
    b.addI32(ANDROID_SYNC_MAX_LATENCY, 2);

    b.add(ANDROID_REQUEST_AVAILABLE_CHARACTERISTICS_KEYS, kCharacteristicsKeys,
          sizeof(kCharacteristicsKeys) / sizeof(kCharacteristicsKeys[0]));
    b.add(ANDROID_REQUEST_AVAILABLE_REQUEST_KEYS, kRequestKeys,
          sizeof(kRequestKeys) / sizeof(kRequestKeys[0]));
    b.add(ANDROID_REQUEST_AVAILABLE_RESULT_KEYS, kResultKeys,
          sizeof(kResultKeys) / sizeof(kResultKeys[0]));

    return b.buildAidl();
}

AidlCameraMetadata buildSessionCharacteristics(const CameraStaticConfig& cfg) {
    MetaBuilder b(8, 256);
    const float zoomRange[] = {1.0f, 4.0f};
    b.add(ANDROID_CONTROL_ZOOM_RATIO_RANGE, zoomRange, 2);
    b.addF32(ANDROID_SCALER_AVAILABLE_MAX_DIGITAL_ZOOM, 4.0f);
    (void)cfg;
    return b.buildAidl();
}

AidlCameraMetadata buildDefaultRequest(const CameraStaticConfig& cfg, RequestTemplate tpl) {
    MetaBuilder b(64, 1024);

    uint8_t intent = ANDROID_CONTROL_CAPTURE_INTENT_PREVIEW;
    uint8_t afMode = cfg.hasAutofocus ? ANDROID_CONTROL_AF_MODE_CONTINUOUS_PICTURE
                                      : ANDROID_CONTROL_AF_MODE_OFF;
    switch (tpl) {
        case RequestTemplate::STILL_CAPTURE:
            intent = ANDROID_CONTROL_CAPTURE_INTENT_STILL_CAPTURE;
            break;
        case RequestTemplate::VIDEO_RECORD:
            intent = ANDROID_CONTROL_CAPTURE_INTENT_VIDEO_RECORD;
            if (cfg.hasAutofocus) afMode = ANDROID_CONTROL_AF_MODE_CONTINUOUS_VIDEO;
            break;
        case RequestTemplate::VIDEO_SNAPSHOT:
            intent = ANDROID_CONTROL_CAPTURE_INTENT_VIDEO_SNAPSHOT;
            if (cfg.hasAutofocus) afMode = ANDROID_CONTROL_AF_MODE_CONTINUOUS_VIDEO;
            break;
        case RequestTemplate::ZERO_SHUTTER_LAG:
            intent = ANDROID_CONTROL_CAPTURE_INTENT_ZERO_SHUTTER_LAG;
            break;
        case RequestTemplate::MANUAL:
            intent = ANDROID_CONTROL_CAPTURE_INTENT_MANUAL;
            afMode = ANDROID_CONTROL_AF_MODE_OFF;
            break;
        case RequestTemplate::PREVIEW:
        default:
            intent = ANDROID_CONTROL_CAPTURE_INTENT_PREVIEW;
            break;
    }

    const uint8_t aeMode = (tpl == RequestTemplate::MANUAL)
                               ? ANDROID_CONTROL_AE_MODE_OFF
                               : ANDROID_CONTROL_AE_MODE_ON;
    const uint8_t ctrlMode = (tpl == RequestTemplate::MANUAL)
                                 ? ANDROID_CONTROL_MODE_OFF
                                 : ANDROID_CONTROL_MODE_AUTO;

    b.addU8(ANDROID_COLOR_CORRECTION_ABERRATION_MODE, ANDROID_COLOR_CORRECTION_ABERRATION_MODE_OFF);
    b.addU8(ANDROID_CONTROL_AE_ANTIBANDING_MODE, ANDROID_CONTROL_AE_ANTIBANDING_MODE_AUTO);
    b.addI32(ANDROID_CONTROL_AE_EXPOSURE_COMPENSATION, 0);
    b.addU8(ANDROID_CONTROL_AE_LOCK, ANDROID_CONTROL_AE_LOCK_OFF);
    b.addU8(ANDROID_CONTROL_AE_MODE, aeMode);
    b.addU8(ANDROID_CONTROL_AE_PRECAPTURE_TRIGGER, ANDROID_CONTROL_AE_PRECAPTURE_TRIGGER_IDLE);
    const int32_t zeroRegion[] = {0, 0, 0, 0, 0};
    b.add(ANDROID_CONTROL_AE_REGIONS, zeroRegion, 5);
    const int32_t fpsRange[] = {15, 30};
    b.add(ANDROID_CONTROL_AE_TARGET_FPS_RANGE, fpsRange, 2);

    b.addU8(ANDROID_CONTROL_AF_MODE, afMode);
    b.add(ANDROID_CONTROL_AF_REGIONS, zeroRegion, 5);
    b.addU8(ANDROID_CONTROL_AF_TRIGGER, ANDROID_CONTROL_AF_TRIGGER_IDLE);
    b.addU8(ANDROID_CONTROL_AWB_LOCK, ANDROID_CONTROL_AWB_LOCK_OFF);
    b.addU8(ANDROID_CONTROL_AWB_MODE, ANDROID_CONTROL_AWB_MODE_AUTO);
    b.addU8(ANDROID_CONTROL_CAPTURE_INTENT, intent);
    b.addU8(ANDROID_CONTROL_EFFECT_MODE, ANDROID_CONTROL_EFFECT_MODE_OFF);
    b.addU8(ANDROID_CONTROL_MODE, ctrlMode);
    b.addU8(ANDROID_CONTROL_SCENE_MODE, ANDROID_CONTROL_SCENE_MODE_DISABLED);
    b.addU8(ANDROID_CONTROL_VIDEO_STABILIZATION_MODE, ANDROID_CONTROL_VIDEO_STABILIZATION_MODE_OFF);
    b.addF32(ANDROID_CONTROL_ZOOM_RATIO, 1.0f);

    b.addU8(ANDROID_EDGE_MODE, ANDROID_EDGE_MODE_FAST);
    b.addU8(ANDROID_FLASH_MODE, ANDROID_FLASH_MODE_OFF);
    b.addI32(ANDROID_JPEG_ORIENTATION, 0);
    b.addU8(ANDROID_JPEG_QUALITY, 92);
    b.addU8(ANDROID_JPEG_THUMBNAIL_QUALITY, 85);
    const int32_t thumb[] = {0, 0};
    b.add(ANDROID_JPEG_THUMBNAIL_SIZE, thumb, 2);

    b.addF32(ANDROID_LENS_FOCUS_DISTANCE, 0.0f);
    b.addU8(ANDROID_NOISE_REDUCTION_MODE, ANDROID_NOISE_REDUCTION_MODE_FAST);
    const int32_t crop[] = {0, 0, cfg.activeWidth, cfg.activeHeight};
    b.add(ANDROID_SCALER_CROP_REGION, crop, 4);
    b.addI64(ANDROID_SENSOR_EXPOSURE_TIME, 16666666LL);
    b.addI64(ANDROID_SENSOR_FRAME_DURATION, 33333333LL);
    b.addI32(ANDROID_SENSOR_SENSITIVITY, 100);
    b.addU8(ANDROID_STATISTICS_FACE_DETECT_MODE, ANDROID_STATISTICS_FACE_DETECT_MODE_OFF);

    return b.buildAidl();
}

